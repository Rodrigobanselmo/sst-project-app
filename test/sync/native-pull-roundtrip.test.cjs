test('real completion, completion removal and collected risk edits still produce their own immutable operations', async (t) => {
  const f = await downloadedVisit(t);
  const { CharacterizationRepository } = require('../../src/repositories/characterizationRepository.ts');
  const { RiskDataRepository } = require('../../src/repositories/riskDataRepository.ts');
  const { characterizationSnapshot } = require('../../src/libs/sync/planner.ts');
  const characters = new CharacterizationRepository(), risks = new RiskDataRepository();
  const parent = f.parents[0], completedAt = new Date('2026-10-24T13:45:56.789Z');
  await characters.update(parent.id, { done_at: completedAt });
  await f.captureVisit(f.journal);
  const completed = (await f.journal.read()).entries.find((e) => e.operation.entityId === parent.id);
  assert.deepEqual(completed.operation.payload, { done_at: completedAt.toISOString() });
  await f.journal.updateReceipt({ operationId: completed.operation.operationId, kind: 'CHARACTERIZATION', entityId: parent.id,
    state: 'APPLIED', receivedAt: '2026-10-24T14:00:00Z', appliedAt: '2026-10-24T14:00:00Z', baseSnapshotHash: '9'.repeat(64),
    snapshot: { ...parent.mobileSync.snapshot, done_at: completedAt.toISOString() } });
  await characters.update(parent.id, { done_at: null });
  const row = parent.homogeneousGroup.riskFactorData[0];
  await risks.update(row.id, { riskId: row.riskId, probability: 4 });
  await f.captureVisit(f.journal);
  const after = await f.journal.read();
  const changes = after.entries.filter((e) => e.operation.entityId === parent.id);
  assert.equal(changes.length, 2);
  assert.deepEqual(changes[0].operation, completed.operation, 'earlier operation must retain its original collected values');
  assert.equal(changes[0].receipt.state, 'APPLIED');
  assert.deepEqual(changes[1].operation.payload, { done_at: null });
  assert.equal(characterizationSnapshot((await characters.findOne(parent.id)).characterization, []).done_at, null);
  const risk = after.entries.find((e) => e.operation.kind === 'RISK_DATA');
  assert.deepEqual(risk.operation.payload, { probability: 4, homogeneousGroupId: parent.id, riskId: row.riskId });
  assert.equal(risk.operation.baseSnapshotHash, row.mobileSync.baseSnapshotHash);
  assert.equal(after.bases[`RISK_DATA:${row.id}`].snapshot.json.nativeFixture, true);
  assert.equal(after.bases[`RISK_DATA:${row.id}`].snapshot.epiDetails[0].trainingCheck, false);
});
