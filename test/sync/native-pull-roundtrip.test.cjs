async function downloadedVisit(t, { splitRisks = false, configure } = {}) {
  const directory = mkdtempSync(join(tmpdir(), 'simplesst-native-roundtrip-'));
  const filename = join(directory, 'visit.db');
  let opened = await openDatabase(filename);
  bindDatabase(opened.db);
  const storageModule = require('../../src/libs/sync/storage.ts');
  // A process restart reconstructs the composition root. Rebind only this test
  // adapter when opening another real SQLite connection in the same Node process.
  storageModule.syncStorage = opened.storage;
  t.after(() => { opened.close(); rmSync(directory, { recursive: true, force: true }); });
  const context = { userId: 11, companyId: randomUUID(), workspaceId: randomUUID() };
  const sourceId = randomUUID(), epcId = randomUUID(), riskIds = [randomUUID(), randomUUID(), randomUUID()];
  await opened.db.write(async () => {
    await opened.db.get('Company').create((r) => { r._raw.id = context.companyId; r.apiId = context.companyId; r.name = 'Empresa nativa sintética'; r.userId = '11'; r.created_at = new Date(); r.updated_at = new Date(); });
    await opened.db.get('Workspace').create((r) => { r._raw.id = context.workspaceId; r.apiId = context.workspaceId; r.companyId = context.companyId; r.name = 'Unidade nativa sintética'; r.userId = '11'; r.created_at = new Date(); r.updated_at = new Date(); });
    await opened.db.get('GenerateSource').create((r) => { r._raw.id = sourceId; r.apiId = sourceId; r.riskId = riskIds[0]; r.name = 'Máquina já recebida da API'; r.userId = '11'; r.status = 'ACTIVE'; r.created_at = new Date(); r.updated_at = new Date(); });
    await opened.db.get('RecMed').create((r) => { r._raw.id = epcId; r.apiId = epcId; r.riskId = riskIds[0]; r.medName = 'Enclausuramento recebido'; r.medType = 'ENG'; r.userId = '11'; r.status = 'ACTIVE'; r.created_at = new Date(); r.updated_at = new Date(); });
  });
  // Server snapshots are intentionally literal, rather than generated by the
  // planner under test. Native SQLite stores the missing numeric date as zero.
  const parents = ['Sala de máquinas', 'Laboratório', 'Atividade de inspeção'].map((name, index) => {
    const id = randomUUID();
    const snapshot = { id, name, description: 'Recebida da API, sem edição', type: 'GENERAL', luminosity: null,
      moisturePercentage: null, noiseValue: null, temperature: null, profileName: null, profileParentId: null,
      done_at: null, status: 'ACTIVE', deleted_at: null, hierarchyIds: [] };
    const riskData = riskIds.filter((_, riskIndex) => splitRisks ? riskIndex === index : index === 0).map((riskId) => {
      const riskIndex = riskIds.indexOf(riskId);
      const riskSnapshot = { id: randomUUID(), riskId, homogeneousGroupId: id, hierarchyId: null, exposure: null,
        activities: null, probability: 3, probabilityAfter: null, startDate: '2026-01-01T12:00:00.000Z',
        endDate: null, json: { meditions: [{ value: 85, date: '2026-01-01' }], nativeFixture: true },
        epiDetails: riskIndex ? [] : [{ epiId: 3, ...epiAnswers }],
        generateSources: riskIndex ? [] : [sourceId], adms: [], recs: [], engs: riskIndex ? [] : [{ recMedId: epcId, efficientlyCheck: false }],
        epis: riskIndex ? [] : [{ epiId: 3, efficientlyCheck: true }] };
      return { ...riskSnapshot, updatedAt: '2026-10-24T12:00:00.000Z',
        generateSources: riskSnapshot.generateSources.map((id) => ({ id })),
        engsToRiskFactorData: riskSnapshot.engs, epiToRiskFactorData: riskSnapshot.epis.map((e) => ({ ...e,
          ...epiAnswers, epi: { equipment: 'Protetor nativo', ca: '999999' } })),
        mobileSync: { baseSnapshotHash: String(riskIndex + 1).repeat(64), snapshot: riskSnapshot } };
    });
    return { ...snapshot, companyId: context.companyId, workspaceId: context.workspaceId,
      created_at: '2026-01-01T12:00:00.000Z', updated_at: '2026-10-24T12:00:00.000Z', photos: [], files: [],
      homogeneousGroup: { hierarchyOnHomogeneous: [], riskFactorData: riskData },
      mobileSync: { baseSnapshotHash: String(index + 4).repeat(64), snapshot } };
  });
  if (configure) await configure({ parents, context, db: opened.db, epcId, riskIds });
  setPullResponse(async () => ({ fullSnapshot: true, latestVersion: Date.parse('2026-10-24T12:00:00Z'), characterizations: parents }));
  const { pullCharacterizations } = require('../../src/libs/sync/pull.ts');
  const { captureVisit } = require('../../src/libs/sync/planner.ts');
  const { createSyncJournal } = require('../../src/libs/sync/storage.ts');
  let journal = await createSyncJournal(context);
  const pull = () => pullCharacterizations(context);
  await pull();
  return { context, filename, get journal() { return journal; }, parents, captureVisit, pull,
    get db() { return opened.db; },
    async reopen() {
      opened.close(); opened = await openDatabase(filename); bindDatabase(opened.db);
      storageModule.syncStorage = opened.storage; journal = await createSyncJournal(context);
    },
  };
}

async function catalogueVisit(t) {
  return downloadedVisit(t, { splitRisks: true, configure: async ({ parents, epcId, riskIds, db }) => {
    await db.write(async () => {
      const globalControl = await db.get('RecMed').find(epcId);
      await globalControl.update((row) => { row.medName = 'Controle global atual'; row.recName = 'Recomendação global atual'; });
    });
    const original = parents[0].homogeneousGroup.riskFactorData[0];
    for (const [index, parent] of parents.slice(0, 2).entries()) {
      const row = parent.homogeneousGroup.riskFactorData[0], snapshot = row.mobileSync.snapshot;
      row.riskId = riskIds[0]; snapshot.riskId = riskIds[0];
      snapshot.assessmentDetails = { catalogSnapshot: { version: 1,
        risk: { id: riskIds[0], name: index ? 'Risco novo deste período' : 'Risco anterior deste período', type: 'FIS', severity: index ? 4 : 2 },
        epis: { '3': { id: 3, equipment: index ? 'Protetor novo' : 'Protetor anterior', ca: index ? '222' : '111' } },
        recMeds: { [epcId]: { id: epcId, medName: index ? 'Controle novo' : 'Controle anterior', recName: index ? 'Recomendação nova' : 'Recomendação anterior' } },
      } };
      snapshot.engs = [{ recMedId: epcId, efficientlyCheck: false }];
      row.engsToRiskFactorData = snapshot.engs;
      snapshot.adms = [epcId]; row.adms = [{ id: epcId }];
      snapshot.recs = [epcId]; row.recs = [{ id: epcId }];
      snapshot.epis = [{ epiId: 3, efficientlyCheck: true }];
      snapshot.epiDetails = [{ epiId: 3, ...epiAnswers }];
      const pin = snapshot.assessmentDetails.catalogSnapshot.epis['3'];
      row.epiToRiskFactorData = [{ epiId: 3, ...epiAnswers, epi: { ...pin } }];
      // A shared risk can have different sources in different visits. The API
      // sends the exact base for each assessment rather than a global override.
      if (index) { snapshot.generateSources = []; row.generateSources = []; }
    }
    assert.equal(original.mobileSync.snapshot.assessmentDetails.catalogSnapshot.epis['3'].ca, '111');
  } });
}

