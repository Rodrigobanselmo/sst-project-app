test('full native parent/risk form saves are unchanged; editing two probabilities creates only two risk operations', async (t) => {
  const f = await downloadedVisit(t, { splitRisks: true });
  const { CharacterizationRepository } = require('../../src/repositories/characterizationRepository.ts');
  const { RiskDataRepository } = require('../../src/repositories/riskDataRepository.ts');
  const { canonical } = require('../../src/libs/sync/journal.ts');
  const characters = new CharacterizationRepository(), risks = new RiskDataRepository();
  for (const parent of f.parents) {
    parent.description = null; parent.mobileSync.snapshot.description = null;
  }
  // Historic API rows can also contain ''. Compare the same semantic absence
  // without changing the stored source/hash used for optimistic concurrency.
  f.parents[2].noiseValue = ''; f.parents[2].mobileSync.snapshot.noiseValue = '';
  await f.pull();
  const originalBases = canonical((await f.journal.read()).bases);
  const fullFormSave = async (parent, probability) => {
    const { characterization } = await characters.findOne(parent.id);
    // Characterization.tsx uses `value || ''` for optional input defaults and
    // persists its getValues() together with the normal risk modal workflow.
    await characters.update(parent.id, {
      name: characterization.name, type: characterization.type,
      description: characterization.description || '', profileName: characterization.profileName || '',
      luminosity: characterization.luminosity || '', noiseValue: characterization.noiseValue || '',
      temperature: characterization.temperature || '', moisturePercentage: characterization.moisturePercentage || '',
    });
    const serverRisk = parent.homogeneousGroup.riskFactorData[0];
    const row = await f.db.get('RiskData').find(serverRisk.id), info = await risks.getRiskDataInfo(row);
    const activities = JSON.parse(row.activities);
    await risks.update(row.id, { ...info, id: row.id, riskId: row.riskId,
      probability: probability ?? row.probability, probabilityAfter: row.probabilityAfter || '',
      exposure: row.exposure || '', realActivity: activities.realActivity || '',
      activities: activities.activities.map((activity) => ({ name: activity.description, description: activity.subActivity,
        id: activity.description + String(activity.subActivity) })),
    });
    assert.equal(row.probabilityAfter, null, 'the actual optional number schema already maps blank to null, never zero');
  };
  for (const parent of f.parents) await fullFormSave(parent);
  await f.captureVisit(f.journal);
  assert.deepEqual((await f.journal.read()).entries, [], 'saving all default form values must not fabricate any operation');
  assert.equal(canonical((await f.journal.read()).bases), originalBases);
  await f.reopen();
  for (const parent of f.parents.slice(0, 2)) await fullFormSave(parent, 4);
  await f.captureVisit(f.journal);
  const entries = (await f.journal.read()).entries;
  assert.equal(entries.length, 2);
  for (const [index, parent] of f.parents.slice(0, 2).entries()) {
    const risk = parent.homogeneousGroup.riskFactorData[0], entry = entries.find((e) => e.operation.entityId === risk.id);
    assert.equal(entry.operation.kind, 'RISK_DATA');
    assert.deepEqual(entry.operation.payload, { probability: 4, homogeneousGroupId: parent.id, riskId: risk.riskId });
    assert.equal(entry.operation.baseSnapshotHash, risk.mobileSync.baseSnapshotHash);
    assert.deepEqual(entry.operation.dependsOn || [], [], 'a risk change must not wait for an unchanged parent');
  }
  assert.equal(entries.some((e) => e.operation.kind === 'CHARACTERIZATION'), false);
  await f.reopen(); await f.captureVisit(f.journal);
  assert.deepEqual((await f.journal.read()).entries, entries, 'restart cannot add defaults, dependencies or duplicate changes');
});

